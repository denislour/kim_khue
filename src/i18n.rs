impl Messages {
    pub fn genre_label(&self, key: &str) -> &'static str {
        match key {
            "wuxia" => self.wuxia,
            "romance" => self.romance,
            "fantasy" => self.fantasy,
            _ => self.other_genre,
        }
    }
}

pub const fn messages(locale: Locale) -> &'static Messages {
    match locale {
        Locale::Vi => &VI,
    }
}

pub(crate) static I18N: &Messages = messages(Locale::Vi);
